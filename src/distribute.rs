    /// The second run must not touch a single file of the first one, and every registered
    /// `sha256_file` must be the hash of the file on disk.
    #[test]
    fn second_batch_never_overwrites_the_first() {
        let base = tmp("twice");
        let input = base.join("in");
        std::fs::create_dir_all(&input).unwrap();
        let files = vec![input.join("a.png"), input.join("b.png")];
        for f in &files {
            textured_png(f);
        }
        let targets = vec![target("r_00000001", "张三"), target("r_00000002", "李四")];
        let regdir = base.join("registry");
        let mut reg = Registry::open(&regdir).unwrap();
        let root = base.join("out");
        let cancel = AtomicBool::new(false);
        let key = key();

        let first = distribute(&files, &targets, &key, &mut reg, &opts(root.clone(), "b_first"), &cancel, &mut |_| {});
        assert_eq!(first.copies.len(), 4);
        let first_hashes: Vec<(PathBuf, String)> =
            first.copies.iter().map(|c| (c.path.clone(), sha_of(&c.path))).collect();
        assert_eq!(files_under(&root).len(), 4);

        let second = distribute(&files, &targets, &key, &mut reg, &opts(root.clone(), "b_second"), &cancel, &mut |_| {});
        assert_eq!(second.copies.len(), 4);
        assert_eq!(files_under(&root).len(), 8);
        for (path, before) in &first_hashes {
            assert_eq!(&sha_of(path), before, "first batch file changed: {}", path.display());
        }
        for copy in first.copies.iter().chain(&second.copies) {
            let entry = registry_entry(&reg, copy.id);
            assert_eq!(entry.sha256_file.as_deref(), Some(sha_of(&copy.path).as_str()));
        }
        let _ = std::fs::remove_dir_all(&base);
    }

    /// Every regular file below `root`, sorted.
    fn files_under(root: &Path) -> Vec<PathBuf> {
        let mut out = vec![];
        let mut stack = vec![root.to_path_buf()];
        while let Some(dir) = stack.pop() {
            for entry in std::fs::read_dir(&dir).unwrap() {
                let path = entry.unwrap().path();
                if path.is_dir() {
                    stack.push(path);
                } else {
                    out.push(path);
                }
            }
        }
        out.sort();
        out
    }
